/** What a fresh clone of a project with "git": "inputs" has: the inputs and MAP.md, and no scan, no graph, no page. */
function freshClone() {
  const r = gitProject({ git: 'inputs' });
  scanAndBuild(r);
  writeJson(path.join(r, 'floorplan', 'descriptions', 'app.json'), { files: { 'src/lib.js': { name: 'Helpers', description: 'Small helpers.' } } });
  writeJson(path.join(r, 'floorplan', 'names.json'), { parts: { app: { name: 'The App' } } });
  build(r);
  for (const f of ['graph.json', 'index.html', 'query.mjs', 'serve.mjs']) fs.rmSync(path.join(r, 'floorplan', f));
  fs.rmSync(path.join(r, 'floorplan', '.cache'), { recursive: true });
  return r;
}
const INPUTS = ['architecture.json', 'names.json', 'descriptions/app.json'];
const snapshot = (r) => INPUTS.map((f) => fs.readFileSync(path.join(r, 'floorplan', f), 'utf8'));

test('status.mjs tells a fresh clone to refresh from its inputs, and tells a worker to read MAP.md first', () => {
  const r = freshClone();
  try {
    const status = run('status.mjs', r);
    assert.match(status, /"git": "inputs"/);
    assert.match(status, /run refresh\.mjs/);
    assert.match(status, /floorplan\/MAP\.md/);
    assert.doesNotMatch(status, /run build\.mjs/, 'a build alone would fail without a scan');
    // with a map built, the hint is still there
    run('refresh.mjs', r);
    const after = run('status.mjs', r);
    assert.match(after, /map built .* covering/);
    assert.match(after, /"git": "inputs": read floorplan\/MAP\.md first/);
  } finally { cleanup(r); }
});

test('refresh.mjs on a fresh clone scans and builds from the inputs, and leaves the inputs as they are', () => {
  const r = freshClone();
  try {
    const before = snapshot(r);
    const out = run('refresh.mjs', r);
    assert.match(out, /no earlier map to compare with/i);
    assert.doesNotMatch(out, /No existing map here|full run/);
    assert.match(out, /^NEXT$/m);
    assert.deepEqual(snapshot(r), before, 'architecture.json, names.json and descriptions/ are untouched');
    const g = readGraph(r);
    assert.equal(g.nodes[0].label, 'The App', 'the fixed name is applied');
    assert.equal(g.files.find((f) => f.p === 'src/lib.js').name, 'Helpers');
    assert.match(mapOf(r), /^### The App \(`app`\)$/m);
    assert.ok(fs.existsSync(path.join(r, 'floorplan', 'index.html')));
    // a second refresh is the ordinary one
    assert.match(run('refresh.mjs', r), /^Floorplan refresh — last map /m);
  } finally { cleanup(r); }
});

