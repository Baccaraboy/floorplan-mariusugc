/** A made-up graph of the shape build.mjs writes, as big as the test needs. */
function syntheticGraph({ parts, files, routes = 0 }) {
  const g = {
    project: { name: 'Big', summary: 'A big one.' },
    meta: { generatedAt: '2026-11-01T08:00:00.000Z', lang: 'en', repos: [], counts: { files: parts * files, loc: parts * files * 10, unassigned: 0 } },
    nodes: [], files: [], routes: [], links: [], flows: [], tour: [], screens: [],
    health: { summary: { high: 0, medium: 0, low: 0 }, issues: [] },
  };
  for (let i = 0; i < parts; i++) {
    g.nodes.push({ id: `p${i}`, parent: null, label: `Part ${i}`, kind: 'service', summary: `Part number ${i}.`, paths: [`src/p${i}/**`], stats: { files, loc: files * 10 } });
    for (let j = 0; j < files; j++) {
      g.files.push({ p: `src/p${i}/f${j}.js`, n: `p${i}`, name: `File ${j}`, d: `Does thing ${j}.`, loc: 10 });
      if (j) g.links.push({ a: `f:src/p${i}/f${j}.js`, b: `f:src/p${i}/f0.js`, k: 'import', w: 1 });
    }
    for (let j = 0; j < routes; j++) g.routes.push({ f: `src/p${i}/f0.js`, m: 'GET', p: `/p${i}/r${j}`, name: `Route ${j}`, d: `Serves ${j}.` });
  }
  return g;
}
