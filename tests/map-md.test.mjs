// MAP.md and "git": "inputs". Teams that build with AI workers (Claude Code, Codex) want every worker to read the map
// before it builds, as text in the repo and not as a web page of over 2 MB. So the build writes floorplan/MAP.md: the
// map as plain text, in the map's language, with a fixed set of sections. And with "git": "inputs" in architecture.json
// the folder ignores only what it generates, so the inputs a person or the AI keeps (architecture.json, names.json,
// targets.json, layers.json, descriptions/) and MAP.md can be committed. Without "git", the folder ignores itself
// completely.
