/** The part of MAP.md from one section's marker up to the next marker. */
function sectionOf(md, name) {
  const from = md.indexOf(`<!-- floorplan:${name} -->`);
  assert.ok(from >= 0, `section "${name}" has its marker`);
  const rest = md.slice(from + 1);
  const to = rest.search(/\n<!-- floorplan:\w+ -->/);
  return to < 0 ? md.slice(from) : md.slice(from, from + 1 + to);
}
/** The text of one part, target, flow or task: from its ### heading up to the next heading. */
function entryOf(md, heading) {
  const lines = md.split('\n');
  const at = lines.indexOf(heading);
  assert.ok(at >= 0, `"${heading}" is in MAP.md`);
  let end = lines.findIndex((l, i) => i > at && /^#{1,6} |^<!-- floorplan:\w+ -->$/.test(l));
  if (end < 0) end = lines.length;
  return lines.slice(at, end).join('\n');
}
/** The items under a bullet that ends in a colon, like "- Endpoints:", without their "  - ". */
function subList(entry, label) {
  const lines = entry.split('\n');
  const at = lines.indexOf(`- ${label}:`);
  if (at < 0) return null;
  const out = [];
  for (let i = at + 1; i < lines.length && lines[i].startsWith('  - '); i++) out.push(lines[i].slice(4));
  return out;
}

/** A small project in its own git repo, so the tests can ask git what it sees under floorplan/. */
