test('the build writes MAP.md with a notice, one title and the same five sections in the same order', () => {
  const md = mapOf(shop);
  const lines = md.split('\n');
  assert.equal(lines[0], '<!-- floorplan:map 1 -->');
  assert.deepEqual(lines.filter((l) => /^# /.test(l)), ['# Shop map']);
  assert.ok(lines.indexOf(NOTICE) > 0 && lines.indexOf(NOTICE) < 6, 'the notice is at the top');
  assert.deepEqual(lines.filter((l) => /^## /.test(l)), ['## Parts', '## Targets', '## Flows', '## Health', '## Recent work']);
  assert.deepEqual(lines.filter((l) => /^<!-- floorplan:\w+ -->$/.test(l)), SECTIONS.map((s) => `<!-- floorplan:${s} -->`));
  // a marker sits right above its heading, so a parser needs no words to find a section
  SECTIONS.forEach((s, i) => assert.equal(lines[lines.indexOf(`<!-- floorplan:${s} -->`) + 1], ['## Parts', '## Targets', '## Flows', '## Health', '## Recent work'][i]));
  assert.ok(md.endsWith('\n') && !md.endsWith('\n\n'));
  // a section with nothing in it says so, and keeps its heading
  for (const s of ['targets', 'flows', 'recent']) assert.match(sectionOf(md, s), /\nNone\.\n/, s);
});

